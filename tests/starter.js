// Generates puzzles-starter.js: first puzzles for total beginners that only use pieces already taught.
// Free captures for each piece (nothing else can be taken), and mate in one with rook or queen.
const Game = require('../chesscore.js')(); const fs = require('fs');
let rs = 4242; const rnd = () => (rs = (rs * 16807) % 2147483647) / 2147483647;
const pick = a => a[Math.floor(rnd() * a.length)];
const SQ = []; 'abcdefgh'.split('').forEach(f => { for (let r = 1; r <= 8; r++) SQ.push(f + r); });
const NAME = { p: 'pawn', n: 'knight', b: 'bishop', r: 'rook', q: 'queen', k: 'king' };
function fenFrom(pcs, side) {
  const rows = []; for (let r = 8; r >= 1; r--) { let row = '', e = 0; for (const f of 'abcdefgh') { const p = pcs[f + r]; if (p) { if (e) { row += e; e = 0; } row += p; } else e++; } if (e) row += e; rows.push(row); }
  return rows.join('/') + ' ' + side + ' - - 0 1';
}
function dist(a, b) { return Math.max(Math.abs(a.charCodeAt(0) - b.charCodeAt(0)), Math.abs(a[1] - b[1])); }
const out = [], seen = new Set();
function addFree(piece, n) {
  let tries = 0, made = 0;
  while (made < n && tries++ < 40000) {
    const pcs = {}, wk = pick(SQ), bk = pick(SQ); if (dist(wk, bk) < 2) continue;
    pcs[wk] = 'K'; pcs[bk] = 'k';
    let ps = pick(SQ); if (pcs[ps]) continue; if (piece === 'p' && /[18]/.test(ps[1])) continue;
    if (piece !== 'k') pcs[ps] = piece === 'p' ? 'P' : piece.toUpperCase(); else ps = wk;
    const tgt = pick(['n', 'b', 'r', 'q']), ts = pick(SQ); if (pcs[ts]) continue; if (/[18]/.test(ts[1]) && tgt === 'p') continue;
    pcs[ts] = tgt;
    // one black pawn as decoy sometimes, not capturable
    if (rnd() < 0.5) { const ds = pick(SQ); if (!pcs[ds] && !/[18]/.test(ds[1])) pcs[ds] = 'p'; }
    const fen = fenFrom(pcs, 'w'), g = new Game(); if (!g.load(fen)) continue;
    if (g.inCheck() || g.inCheck(8)) continue;
    const caps = g.moves().filter(m => m.captured);
    if (caps.length !== 1 || caps[0].to !== ts) continue;
    const m = caps[0]; if (m.piece !== piece) continue;
    g.move(m); if (g.moves().some(x => x.to === ts && x.captured)) continue; // must be free: no recapture
    if (g.gameOver()) continue;
    const key = fen.split(' ')[0]; if (seen.has(key)) continue; seen.add(key);
    made++;
    out.push({ title: 'Free ' + NAME[tgt], theme: 'hanging', r: 0, pieces: [piece], fen, sol: [m.from + m.to],
      explain: 'Your ' + NAME[piece] + ' can take the ' + NAME[tgt] + ' on ' + ts + ', and nothing can take it back. A free ' + NAME[tgt] + '!' });
  }
}
function addMate(piece, n) {
  let tries = 0, made = 0;
  while (made < n && tries++ < 200000) {
    const pcs = {}, bk = pick(['a8', 'b8', 'c8', 'd8', 'e8', 'f8', 'g8', 'h8', 'h1', 'a1', 'a5', 'h5', 'h7', 'a3']), wk = pick(SQ);
    if (dist(wk, bk) < 2) continue; pcs[wk] = 'K'; pcs[bk] = 'k';
    const ps = pick(SQ); if (pcs[ps]) continue; pcs[ps] = piece.toUpperCase();
    const fen = fenFrom(pcs, 'w'), g = new Game(); if (!g.load(fen)) continue;
    if (g.inCheck() || g.inCheck(8)) continue;
    const mates = g.moves().filter(m => { g.move(m); const ok = g.inCheckmate(); g.undo(); return ok; });
    if (mates.length !== 1) continue;
    // not mate already in the other direction, and the black king is not stalemated
    const key = fen.split(' ')[0]; if (seen.has(key)) continue; seen.add(key);
    made++;
    out.push({ title: 'Mate in one', theme: 'mate', r: 0, pieces: [piece], mate: 1, fen, sol: [mates[0].from + mates[0].to],
      explain: mates[0].san + ' is checkmate: the king is attacked and every escape square is covered.' });
  }
}
addFree('r', 10); addFree('b', 8); addFree('q', 8); addFree('n', 10); addFree('p', 10); addFree('k', 6);
addMate('r', 10); addMate('q', 10);
const R = { r: 120, b: 140, q: 150, n: 170, p: 180, k: 190 };
out.forEach((p, i) => { p.id = 's' + String(i + 1).padStart(3, '0'); p.r = p.theme === 'mate' ? (p.pieces[0] === 'q' ? 240 : 280) : R[p.pieces[0]]; });
const by = {}; out.forEach(p => { const k = p.theme + ':' + p.pieces[0]; by[k] = (by[k] || 0) + 1; });
console.log(out.length, by);
fs.writeFileSync('puzzles-starter.js', '// First puzzles for total beginners: only pieces already taught. Generated by tests/starter.js.\nvar PUZZLES_STARTER = ' + JSON.stringify(out, null, 0).replace(/\},\{/g, '},\n  {') + ';\nif (typeof PUZZLES !== \'undefined\') PUZZLES.push.apply(PUZZLES, PUZZLES_STARTER);\nif (typeof module !== \'undefined\') module.exports = PUZZLES_STARTER;\n');
